// Nombre visible del icono (sin sinónimos).
export const iconLabel = (num) => ICON_NAMES[num]?.[0] || `Icono ${num}`;

// Texto plano para buscar: nombre + sinónimos + número, sin tildes y en
// minúsculas, para que "baño" encuentre "bano" y al revés.
const COMBINING = /[̀-ͯ]/g;
const deburr = (s) => s.normalize('NFD').replace(COMBINING, '').toLowerCase();
export const normalizeQuery = deburr;

const HAYSTACK = {};
export const iconHaystack = (num) => {
  if (!HAYSTACK[num]) HAYSTACK[num] = deburr([...(ICON_NAMES[num] || []), String(num)].join(' '));
  return HAYSTACK[num];
};

// true si el icono casa con la búsqueda. Cada palabra debe aparecer (AND), así
// "luz baño" filtra mejor que cualquiera de las dos sola.
export const iconMatches = (num, query) => {
  const terms = deburr(query).split(/\s+/).filter(Boolean);
  if (!terms.length) return true;
  const hay = iconHaystack(num);
  return terms.every((t) => hay.includes(t));
};
